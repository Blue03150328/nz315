import fs from 'node:fs'
import assert from 'node:assert/strict'

// 核对本次用户实体扫码及USB归档回执，不生成或注入扫码事件。
const root=new URL('../../../.tmp/device-scan-20261017/',import.meta.url)
const load=name=>JSON.parse(fs.readFileSync(new URL(name+'.json',root),'utf8'))
const internal=load('internal-optical-report'),external=load('external-optical-report')
const invalid=load('invalid-optical-report'),baseline=load('paused-baseline-report')
const paused=load('paused-scan-report'),resumed=load('resumed-scan-report'),restored=load('restored-report')
const events=report=>report.snapshot.recent.map(row=>row.event).sort((a,b)=>a.sequence-b.sequence)
const code1='https://www.nz315.cn/trace?code='+'0'.repeat(31)+'1'
const code2='https://www.nz315.cn/trace?code='+'0'.repeat(31)+'2'
assert.equal(internal.counts.total,17)
assert.equal(internal.counts.internal,1)
assert.equal(internal.counts.duplicates,16)
assert.equal(internal.counts.exceptions,0)
assert.ok(events(internal).every(event=>event.rawCode===code1))
assert.equal(external.counts.total,19)
assert.equal(external.counts.collected,2)
assert.equal(external.counts.internal,1)
assert.equal(external.counts.external,1)
assert.equal(external.counts.duplicates,17)
assert.deepEqual(events(external).slice(17).map(e=>[e.rawCode,e.classification,e.kind]),[
 ['https://scan-probe.invalid/trace?id=OPTICAL-20261017-001','external','valid'],
 ['https://scan-probe.invalid/trace?id=OPTICAL-20261017-001','external','duplicate'],
])
assert.equal(invalid.counts.total,20)
assert.equal(invalid.counts.collected,2)
assert.equal(invalid.counts.exceptions,1)
assert.equal(invalid.lastKind,'invalid')
assert.equal(invalid.lastRaw,'INVALID-SCAN-PROBE-20261017')
assert.equal(paused.armed,false)
assert.equal(paused.lastKind,'paused')
assert.equal(paused.lastRaw,code2)
assert.ok(paused.pausedInputsThisProcess>baseline.pausedInputsThisProcess)
assert.deepEqual(paused.counts,baseline.counts)
assert.deepEqual(paused.snapshot.recent,baseline.snapshot.recent)
assert.equal(resumed.counts.total,21)
assert.equal(resumed.counts.collected,3)
assert.equal(resumed.counts.internal,2)
assert.equal(resumed.counts.external,1)
assert.equal(resumed.lastRaw,code2)
assert.equal(resumed.lastKind,'valid')
assert.equal(restored.armed,false)
assert.deepEqual(restored.counts,resumed.counts)
assert.deepEqual(restored.snapshot,resumed.snapshot)
const all=events(restored)
assert.equal(all.length,21)
assert.equal(new Set(all.map(e=>e.eventId)).size,21)
assert.deepEqual(all.map(e=>e.sequence),Array.from({length:21},(_,i)=>i+1))
assert.ok(all.every(e=>!/[\r\n]/.test(e.rawCode)))
const beforePid=fs.readFileSync(new URL('process-before.txt',root),'utf8').trim()
const afterPid=fs.readFileSync(new URL('process-after.txt',root),'utf8').trim()
assert.match(beforePid,/^\d+$/)
assert.match(afterPid,/^\d+$/)
assert.notEqual(beforePid,afterPid)
for(const report of [internal,external,invalid,paused,resumed])assert.equal(report.channel,'广播：android.intent.ACTION_DECODE_DATA')
console.log('实机回执核对通过：内码、外码、重复、异常、暂停不保存、恢复重扫、进程重开持久化')
console.log('最终21条：有效3（内码2／外码1）、重复17、异常1；21个原UUID及序号在进程重开后保持')
console.log('暂停测试新增输入次数：'+(paused.pausedInputsThisProcess-baseline.pausedInputsThisProcess))
